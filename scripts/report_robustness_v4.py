    assert load(RUN / "audit.json")["passed"]
    development = load(RUN / "frozen_indel_seed71/metrics.json")
    holdout = load(RUN / "holdout_indel_seed72/metrics.json")
    first = RUN / "real_chr22_22100000_22600000"
    second = RUN / "real_holdout_chr22_24100000_24600000"
    real = [
        dict(
            interval="22.1-22.6 Mb",
            method="v3",
            **load(first / "annotation_metrics_extended.json"),
        ),
        dict(
            interval="24.1-24.6 Mb",
            method="v3",
            **load(second / "ungapped.annotation_metrics.json"),
        ),
        dict(
            interval="24.1-24.6 Mb",
            method="gap refinement",
            **load(second / "gapped.annotation_metrics.json"),
        ),
    ]
    posthoc = second / "posthoc_unique"
